import fs from 'fs';
import { getCompletionBlock, getAutocompleteDir, getBashrcFile, getAutocompleteFile, backupBashRc, validateBinName } from './helpers.js';

/**
 * Template for bash autocomplete.
 *
 * - The words being completed are passed after `--`, so they are never parsed as options of the binary.
 * - Suggestions are read one per line and never go through shell expansion
 *   (no `compgen -W`), so a suggestion like `$(cmd)` is never executed.
 * - `-o default` lets bash fall back to file completion when there is no suggestion.
 * @param bin_name name of binary
 * @returns the content of the bash completion file
 */
export const generateBashTemplate = (bin_name: string) => `
# bash completion for ${bin_name}, generated by @naerth/commander-autocomplete
_${bin_name}_completion() {
    local cur="\${COMP_WORDS[COMP_CWORD]}"
    local suggestion
    COMPREPLY=()

    while IFS= read -r suggestion; do
        if [[ -n "$suggestion" && "$suggestion" == "$cur"* ]]; then
            COMPREPLY+=("$(printf '%q' "$suggestion")")
        fi
    done < <(${bin_name} completion -- "\${COMP_WORDS[@]:0:COMP_CWORD+1}" 2>/dev/null)
}

complete -o bashdefault -o default -F _${bin_name}_completion ${bin_name}
`;

/**
 * Create and write autocomplete file, and source it from .bashrc
 * @param bin_name name of binary
 * @throws {Error} If the binary name is invalid
 */
export function setupBash(bin_name: string) {
    // Validate bin_name to prevent command injection and path traversal
    validateBinName(bin_name);

    fs.mkdirSync(getAutocompleteDir(), { mode: 0o755, recursive: true });
    const completionFile = getAutocompleteFile(bin_name);

    console.log(`Write ${completionFile}`);
    fs.writeFileSync(completionFile, generateBashTemplate(bin_name));

    const bashrcFile = getBashrcFile();
    const completionBlock = getCompletionBlock(completionFile);
    const bashrcContent = fs.existsSync(bashrcFile)
        ? fs.readFileSync(bashrcFile, { encoding: 'utf-8' })
        : '';

    // Nothing to do if .bashrc already sources the completion file
    if (bashrcContent.split('\n').some(line => line.trim() === completionBlock.trim())) {
        console.log('.bashrc is already configured');
        return;
    }

    if (bashrcContent) {
        const backupFile = backupBashRc(bashrcFile);
        console.log(`Backup .bashrc to ${backupFile}`);
    }

    // Never glue the completion block to an unterminated last line
    const separator = bashrcContent && !bashrcContent.endsWith('\n') ? '\n' : '';

    console.log(`Write .bashrc`);
    fs.appendFileSync(bashrcFile, separator + completionBlock);
}
